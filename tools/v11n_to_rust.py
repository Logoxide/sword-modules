#!/usr/bin/env python3
"""Turn data/versification.json into src/versification/data.rs.

The JSON holds facts (book names, OSIS ids, abbreviations and verse counts per
chapter) for each of SWORD's built-in versification systems. This writes them
as static Rust tables; identical verse-count lists are shared.

    python3 tools/v11n_to_rust.py > src/versification/data.rs
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
systems = json.load(open(os.path.join(ROOT, "data", "versification.json"), encoding="utf-8"))

counts = {}
order = []


def counts_name(verses):
    key = tuple(verses)
    if key not in counts:
        counts[key] = f"C{len(order)}"
        order.append(key)
    return counts[key]


def book(b):
    return f'    Book {{ name: {json.dumps(b["name"])}, osis: {json.dumps(b["osis"])}, abbrev: {json.dumps(b["abbrev"])}, verses: {counts_name(b["verses"])} }},'


body = []
for s in systems:
    for part in ("ot", "nt"):
        body.append(f"static {s['name'].upper()}_{part.upper()}: &[Book] = &[")
        body.extend(book(b) for b in s[part])
        body.append("];")

print("// Generated by tools/v11n_to_rust.py from data/versification.json; do not edit.")
print("#![allow(clippy::all)]")
print()
print("/// One book of a system: its names and the verse count of each chapter.")
print("pub(super) struct Book {")
print("    pub name: &'static str,")
print("    pub osis: &'static str,")
print("    pub abbrev: &'static str,")
print("    pub verses: &'static [u8],")
print("}")
print()
print("/// One versification system as listed in the data file.")
print("pub(super) struct System {")
print("    pub name: &'static str,")
print("    pub ot: &'static [Book],")
print("    pub nt: &'static [Book],")
print("}")
print()
for i, key in enumerate(order):
    print(f"const C{i}: &[u8] = &[{', '.join(map(str, key))}];")
print()
print("\n".join(body))
print()
print("pub(super) static SYSTEMS: &[System] = &[")
for s in systems:
    n = s["name"].upper()
    print(f'    System {{ name: {json.dumps(s["name"])}, ot: {n}_OT, nt: {n}_NT }},')
print("];")
